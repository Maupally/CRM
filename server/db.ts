/**
 * Postgres access behind a tiny interface, with two engines:
 *  - a real server (Supabase, Neon, Vercel Postgres) when DATABASE_URL / POSTGRES_URL is set,
 *  - PGlite (Postgres compiled to WebAssembly) in-process otherwise — local dev and tests,
 *    nothing to install.
 *
 * Every table lives in the `crm` schema, so the CRM can share a database with another app.
 */
import fs from 'node:fs';
import path from 'node:path';

export type Row = Record<string, any>;

export interface Q {
  all<T = Row>(sql: string, params?: unknown[]): Promise<T[]>;
  get<T = Row>(sql: string, params?: unknown[]): Promise<T | undefined>;
  /** Returns the number of affected rows. */
  run(sql: string, params?: unknown[]): Promise<number>;
}

export interface DB extends Q {
  tx<T>(fn: (q: Q) => Promise<T>): Promise<T>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
}

/** `?` placeholders → `$1, $2 …` (none of our SQL has a literal ? inside quotes). */
function pg(sql: string): string {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

