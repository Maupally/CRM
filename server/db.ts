/* ------------------------------------------------------------ server Postgres */

/**
 * Connection strings from Supabase and Neon carry libpq-only options (sslmode,
 * channel_binding, supa, pgbouncer) that postgres.js would forward to the server
 * as settings — and the server rejects them. SSL is configured explicitly instead.
 */
export function cleanUrl(url: string): string {
  const u = new URL(url);
  for (const k of ['sslmode', 'channel_binding', 'supa', 'pgbouncer', 'sslrootcert', 'options']) u.searchParams.delete(k);
  return u.toString();
}

async function openRemote(url: string): Promise<DB> {
  const { default: postgres } = await import('postgres');
  const local = /localhost|127\.0\.0\.1/.test(url);
  const sql = postgres(cleanUrl(url), {
    prepare: false,                        // required by Supabase / Neon poolers (transaction mode)
    ssl: local ? false : 'require',
    max: 5,
    idle_timeout: 20,
    onnotice: () => {},
  });
  const make = (s: any): Q => ({
    all: async (q, p = []) => (await s.unsafe(pg(q), p as any[])) as any[],
    get: async (q, p = []) => ((await s.unsafe(pg(q), p as any[])) as any[])[0],
    run: async (q, p = []) => Number((await s.unsafe(pg(q), p as any[])).count) || 0,
  });
  return {
    ...make(sql),
    tx: (fn) => sql.begin((t: any) => fn(make(t))) as any,
    exec: async (q) => { await sql.unsafe(q); },
    close: () => sql.end(),
  };
}

/* ------------------------------------------------------------ embedded PGlite */

async function openEmbedded(dir: string): Promise<DB> {
  const { PGlite } = await import('@electric-sql/pglite');
  if (dir !== 'memory://') fs.mkdirSync(path.dirname(dir), { recursive: true });
  const db = new PGlite(dir === 'memory://' ? undefined : dir);
  const make = (s: any): Q => ({
    all: async (q, p = []) => (await s.query(pg(q), p)).rows,
    get: async (q, p = []) => (await s.query(pg(q), p)).rows[0],
    run: async (q, p = []) => (await s.query(pg(q), p)).affectedRows ?? 0,
  });
  return {
    ...make(db),
    tx: (fn) => db.transaction((t: any) => fn(make(t))),
    exec: async (q) => { await db.exec(q); },
    close: () => db.close(),
  };
}

export function databaseUrl(): string {
  return process.env.DATABASE_URL || process.env.POSTGRES_URL || process.env.SUPABASE_DB_URL || '';
}

/** Opens the database and makes sure the tables exist. */
export async function openDb(target = databaseUrl() || process.env.PGLITE_DIR || path.resolve('data/pglite')): Promise<DB> {
  if (process.env.VERCEL && !/^postgres/.test(target)) {
    throw new Error('Baza danych nie jest podłączona. W Vercel: Storage → Create Database (Neon albo Supabase) → Connect, ' +
      'albo dodaj zmienną DATABASE_URL. Potem Redeploy.');
  }
  const db = /^postgres(ql)?:\/\//.test(target) ? await openRemote(target) : await openEmbedded(target);
  await db.exec(SCHEMA);
  return db;
}

/** Insert many rows with few round trips — matters a lot over the network. */
export async function insertMany(q: Q, table: string, cols: string[], rows: unknown[][], chunk = 400) {
  for (let i = 0; i < rows.length; i += chunk) {
    const part = rows.slice(i, i + chunk);
    const values = part.map(() => `(${cols.map(() => '?').join(', ')})`).join(', ');
    await q.run(`INSERT INTO ${table} (${cols.join(', ')}) VALUES ${values}`, part.flat());
  }
}

